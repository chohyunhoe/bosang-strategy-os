'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const api = await import(pathToFileURL(path.resolve(__dirname, '../browser/product-v2/document-workflow.js')));
  const { registerDocument, attachDocumentArtifact, createDocumentHandoff, importDocumentExecution, sha256Bytes, changeDocument, REVIEW_CHECKS } = api;
  const digest = await sha256Bytes(new TextEncoder().encode('synthetic document'));
  let rows = registerDocument([], { title:'검토문',purpose:'내부 검토',owner:'A',template_ref:'v1',source_ref:'합성 원본',actor:'A' });
  const id = rows[0].id, file = { name:'synthetic.txt',size:18,sha256:digest };
  rows = attachDocumentArtifact(rows,id,file,'A');
  const requested = await createDocumentHandoff(rows,id,'Synthetic instructions only','SYNTHETIC','A');
  rows=requested.rows; const job=requested.job;
  assert.equal(job.status,'READY'); assert.equal(job.attempts,0,'dispatcher must claim before execution');
  assert.equal(JSON.stringify(rows).includes('Synthetic instructions only'),false,'do not retain prompt in case metadata');
  const receipt={schema_version:'lk-bso-receipt/1.0',...job.bso_context,schema_version:'lk-bso-receipt/1.0',job_id:job.job_id,input_sha256:job.input_sha256,output_sha256:digest,execution_id:'SYNTHETIC_EXECUTION',status:'NEEDS_GPT_REVIEW',human_approved:false};
  const imported=importDocumentExecution(rows,id,receipt,'A');
  assert.equal(imported[0].status,'DRAFT'); assert.deepEqual(imported[0].checks,{});
  assert.equal(imported[0].execution_receipts.length,1);
  assert.throws(()=>importDocumentExecution(imported,id,receipt,'A'),'duplicate result');
  for(const patch of [{revision:2},{input_sha256:'0'.repeat(64)},{artifact_sha256:'1'.repeat(64)},{human_approved:true},{job_id:'OTHER'},{status:'DONE'}])assert.throws(()=>importDocumentExecution(rows,id,{...receipt,...patch},'A'));
  await assert.rejects(createDocumentHandoff(rows,id,'confidential','CONFIDENTIAL','A'));
  for(const check of REVIEW_CHECKS) rows=changeDocument(rows,id,'CHECK',{actor:'A',reference:'검수기록',check});
  rows=changeDocument(rows,id,'APPROVE',{actor:'검토자',reference:'승인메모'});
  const same=attachDocumentArtifact(rows,id,file,'A'); assert.equal(same[0].status,'APPROVED','same bytes do not invalidate approval');
  const changed=attachDocumentArtifact(rows,id,{...file,sha256:'2'.repeat(64)},'A');
  assert.equal(changed[0].revision,2);assert.equal(changed[0].status,'DRAFT');assert.equal(changed[0].approval,null);
  assert.throws(()=>importDocumentExecution(changed,id,receipt,'A'),'old revision result must not attach to new file');
  assert.equal(rows[0].status,'APPROVED','failed imports do not mutate input');
  console.log('document_execution_handoff.test.js passed: byte fingerprints, revision invalidation, job binding, replay rejection, human approval separation');
})().catch(error=>{console.error(error);process.exitCode=1;});

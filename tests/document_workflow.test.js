'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

(async () => {
  const base = path.resolve(__dirname, '../browser/product-v2');
  const { registerDocument, changeDocument, documentProgress, validateDocumentWorkflow, REVIEW_CHECKS } = await import(pathToFileURL(path.join(base, 'document-workflow.js')));
  const { CaseStore } = await import(pathToFileURL(path.join(base, 'case-store.js')));
  const { SessionCaseRegistry } = await import(pathToFileURL(path.join(base, 'case-registry.js')));
  const input = { title: '검토용 공문', purpose: '기관 제출 검토', owner: '담당자 A', template_ref: '공식서식 v1', source_ref: '검토용 원본 A', actor: '기록자 A' };
  const proof = { actor: '검토자 A', reference: '검토메모 A' };
  let rows = registerDocument([], input);
  const id = rows[0].id;
  assert.equal(documentProgress(rows[0]).status, 'PARTIAL');
  for (const action of ['APPROVE', 'SUBMIT']) assert.throws(() => changeDocument(rows, id, action, proof));
  assert.throws(() => registerDocument([], { ...input, template_ref: '' }));
  assert.throws(() => changeDocument(rows, id, 'CHECK', { ...proof, check: 'SOURCE', reference: '' }));
  assert.throws(() => changeDocument(rows, id, 'CHECK', { ...proof, check: 'UNKNOWN' }));
  assert.throws(() => changeDocument(rows, 'OTHER_CASE_DOCUMENT', 'REVISE', proof));
  for (const check of REVIEW_CHECKS) rows = changeDocument(rows, id, 'CHECK', { ...proof, check });
  assert.equal(rows[0].status, 'REVIEWED');
  const reviewed = JSON.stringify(rows);
  assert.throws(() => changeDocument(rows, id, 'SUBMIT', proof));
  assert.equal(JSON.stringify(rows), reviewed, 'failed transitions must be atomic');
  rows = changeDocument(rows, id, 'APPROVE', proof);
  assert.equal(documentProgress(rows[0]).status, 'PARTIAL', 'approval is not submission');
  rows = changeDocument(rows, id, 'ADD_FOLLOWUP', { ...proof, title: '회신 확인', owner: '담당자 B', due_date: '2026-11-10' });
  assert.throws(() => changeDocument(rows, id, 'ADD_FOLLOWUP', { ...proof, title: '잘못된 기한', owner: 'B', due_date: '2026-02-30' }));
  rows = changeDocument(rows, id, 'SUBMIT', { ...proof, reference: '접수증 A' });
  assert.deepEqual(documentProgress(rows[0], '2026-11-11'), { status: 'PARTIAL', pending: 1, overdue: 1 });
  assert.equal(documentProgress(rows[0], '2026-11-10').overdue, 0);
  rows = changeDocument(rows, id, 'COMPLETE_FOLLOWUP', { ...proof, task_id: 'TASK_1' });
  assert.equal(documentProgress(rows[0]).status, 'DONE');
  assert.throws(() => changeDocument(rows, id, 'COMPLETE_FOLLOWUP', { ...proof, task_id: 'TASK_1' }));
  const previous = JSON.stringify(rows);
  rows = changeDocument(rows, id, 'REVISE', { ...proof, reference: '수정본 B' });
  assert.equal(rows[0].revision, 2);
  assert.equal(rows[0].status, 'DRAFT');
  assert.deepEqual(rows[0].checks, {});
  assert.equal(rows[0].approval, null);
  assert.equal(rows[0].submission, null);
  assert.ok(rows[0].history.some((event) => event.action === 'SUBMIT' && event.revision === 1));
  assert.equal(rows[0].followups[0].status, 'DONE', 'historical followups survive revision');
  assert.equal(JSON.parse(previous)[0].status, 'SUBMITTED', 'input snapshots stay immutable');
  assert.throws(() => changeDocument(rows, id, 'APPROVE', proof));
  assert.throws(() => validateDocumentWorkflow([{ ...rows[0], status: 'SUBMITTED' }]));
  assert.throws(() => validateDocumentWorkflow([rows[0], rows[0]]));
  const staleChecks = Object.fromEntries(REVIEW_CHECKS.map((key) => [key, { ...proof, revision: 1, recorded_at: new Date().toISOString() }]));
  assert.throws(() => validateDocumentWorkflow([{ ...rows[0], checks: staleChecks, status: 'REVIEWED' }]));
  const store = new CaseStore();
  const registry = new SessionCaseRegistry(store);
  const first = registry.ensureActive();
  store.state.documentWorkflow = rows; store.emit();
  assert.equal(registry.hasUnsavedWork(), true, 'document-only work must trigger unsaved warning');
  registry.startNew();
  assert.deepEqual(store.state.documentWorkflow, [], 'new case must not inherit documents');
  registry.switchTo(first);
  assert.deepEqual(store.state.documentWorkflow, rows, 'switching restores document progress');
  const backup = registry.exportBundle();
  const restored = new CaseStore();
  const registry2 = new SessionCaseRegistry(restored);
  registry2.importBundle(backup);
  assert.deepEqual(restored.state.documentWorkflow, rows);
  const before = JSON.stringify(restored.snapshot());
  const forged = JSON.parse(JSON.stringify(backup));
  forged.entries.find((entry) => entry.id === first).snapshot.documentWorkflow[0].status = 'APPROVED';
  assert.throws(() => registry2.importBundle(forged));
  assert.equal(JSON.stringify(restored.snapshot()), before, 'invalid backup must not replace live state');
  restored.restoreSnapshot({ caseInfo: {} });
  assert.deepEqual(restored.state.documentWorkflow, [], 'older backups remain supported');
  registry.destroy(); registry2.destroy();
  console.log('document_workflow.test.js passed: gates, revision, followups, case isolation, backup compatibility');
})().catch((error) => { console.error(error); process.exitCode = 1; });
